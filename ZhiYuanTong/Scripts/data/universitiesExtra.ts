const HOT_CITY = ['北京', '上海', '深圳', '广州', '杭州', '南京', '苏州', '厦门', '珠海', '东莞', '佛山', '宁波', '无锡', '天津', '青岛', '武汉', '成都', '长沙', '合肥', '济南', '福州', '大连', '常州', '南通', '温州']
const REMOTE_CITY = ['兰州', '西宁', '银川', '乌鲁木齐', '拉萨', '呼和浩特', '石河子', '克拉玛依', '昌吉', '天水', '张掖', '石嘴山', '遵义', '拉萨', '雅安', '阜新']

function cityFactor(city: string): number {
  if (HOT_CITY.includes(city)) return 1.07
  if (REMOTE_CITY.includes(city)) return 0.9
  return 0.97
}

function makeSeed([name, prov, city, level, kind, base, baseHis]: Row): UniversitySeed {
  const k = KIND_PROFILE[kind]
  const lv = LEVEL_ADJ[level]
  const hint = NAME_HINT.find((h) => h.re.test(name))
  const strengths = hint?.strengths ?? k.strengths
  const majors = hint?.majors ?? k.majors
  const f = cityFactor(city)
  const salary = Math.round((k.salary * lv.salary * f) / 100) * 100
  const baoyan = Math.round(lv.baoyan * (kind === '医药' ? 0.85 : kind === '理工' || kind === '军工' ? 1.1 : 1))
  const further = Math.round(lv.further * (kind === '医药' ? 1.05 : 1))
  return {
    name,
    prov,
    city,
    level,
    kind,
    base,
    baseHis: baseHis ?? base - 6,
    strengths,
    majors,
    baoyan: Math.max(0, baoyan),
    further: Math.min(96, Math.max(5, further)),
    employRate: +Math.min(98.5, Math.max(80, k.employRate + lv.employ + (f - 1) * 8)).toFixed(1),
    salary,
    industries: k.industries,
    employers: k.employers,
  }
}

